#!/data/data/com.termux/files/usr/bin/bash
# gen_std.sh -- turns std/*.j (the standard library, written in J2K) into
# jcmp/jc_std.j, a function that puts the text in front of a program that says
# "import std". Run it after changing a file in std/, then ./bootstrap.sh.
cd "$(dirname "$0")"
python3 - <<'PY'
# the units of the standard library, in the order they are read; a category of `import <name>` is a set of units (bit n = unit n)
units = [
    ["sys", "result", "arena"],                 # 0 core
    ["math", "num"],                            # 1 number
    ["str", "encode", "fmt", "regex"],          # 2 text
    ["fs", "fsdir", "path"],                    # 3 files
    ["system", "log"],                          # 4 system
    ["time", "date"],                           # 5 time
    ["collections", "json", "csv", "toml"],     # 6 data
    ["hash", "crypto"],                         # 7 crypto
    ["net"],                                    # 8 net
]
unit_names = ["core", "number", "text", "files", "system", "time", "data", "crypto", "net"]
files = [f for u in units for f in u]
import os
os.makedirs("Library", exist_ok=True)
def libtext(fs):
    # exactly the lines that put() writes: every line of every file, and a line for the empty piece after the last newline
    out = []
    for f in fs:
        for line in open("std/%s.j" % f).read().split("\n"):
            out.append(line + "\n")
    return "".join(out)
def writelib(name, fs):
    open("Library/%s.j" % name, "w").write(libtext(fs))
def gen(name, files, doc, libname):
    writelib(libname, files)
    out = ['void %s() {' % name,
           '    if lx_depth >= 15 { die("imports nested too deeply"); }',
           '    stk_pos[lx_depth] = cur_pos;', '    stk_line[lx_depth] = cur_line;',
           '    stk_ls[lx_depth] = cur_line_start;', '    stk_len[lx_depth] = cur_len;',
           '    str_copy(@lvl_name + (lx_depth + 1) * 128, @lvl_name + lx_depth * 128, 128);',
           '    lx_depth += 1;', '    lvl_lib[lx_depth] = 1;', '    cur_base = lx_depth * 524288;', '    cur_len = 0;']
    out.append('    ext_put("%s");' % libname)
    out += ['    src_bufs[cur_base + cur_len] = 0;', '    cur_pos = 0;', '    cur_line = 1;',
            '    cur_line_start = 0;', '}', '']
    return ["// " + doc] + out
text = ['// jc_std.j -- GENERATED by gen_std.sh. Do not edit. The text of the library is in the folder Library/ (made from std/*.j); these functions read it.', '']
def gen_units(name, units, doc):
    out = ['// ' + doc, 'void %s(int mask) {' % name,
           '    if lx_depth >= 15 { die("imports nested too deeply"); }',
           '    stk_pos[lx_depth] = cur_pos;', '    stk_line[lx_depth] = cur_line;',
           '    stk_ls[lx_depth] = cur_line_start;', '    stk_len[lx_depth] = cur_len;',
           '    str_copy(@lvl_name + (lx_depth + 1) * 128, @lvl_name + lx_depth * 128, 128);',
           '    lx_depth += 1;', '    lvl_lib[lx_depth] = 1;', '    cur_base = lx_depth * 524288;', '    cur_len = 0;']
    for n, u in enumerate(units):
        writelib(unit_names[n], u)
        out.append('    if (mask & %d) != 0 {' % (1 << n))
        out.append('        ext_put("%s");' % unit_names[n])
        out.append('    }')
    out += ['    src_bufs[cur_base + cur_len] = 0;', '    cur_pos = 0;', '    cur_line = 1;',
            '    cur_line_start = 0;', '}', '']
    return out
text += gen_units("push_std_units", units, "push_std_units(mask): the units of the standard library in the mask become a new \"file\" that is read next (core, number, text, files, system, time, data, crypto).")
# the libraries that come with the compiler (folder Library): cpu, vector and matrix; the others are downloaded with jget (build/libs and Jcmp-libs/libs)
for lib in ("cpu", "vector", "matrix"):
    writelib(lib, [lib])
os.makedirs("build/libs", exist_ok=True)
for lib in ("simd", "quat", "complex", "stats", "canvas", "screen", "neuron", "deflate", "png", "qr", "sprite", "tilemap", "phys2d", "profile", "jobs", "spritebatch", "shaders", "compute", "tasks", "canvas2d", "glcanvas", "glapp", "compute", "gamej", "gpu", "native", "opengl3", "vulkan", "web", "telegram", "discord"):
    t = libtext([lib])
    open("build/libs/%s.j" % lib, "w").write(t)
    if os.path.isdir(os.path.expanduser("~/Jcmp-libs/libs")):
        open(os.path.expanduser("~/Jcmp-libs/libs/%s.j" % lib), "w").write(t)
text += gen("push_prelude", ["rt_heap", "rt_hw", "rt_mem", "rt_arr", "rt_str", "rt_in", "rt_fp", "rt_mt", "rt_a32"], "push_prelude(): the runtime, read in front of every program: heap + panic, hardware (Cpu Atomic Cache Bit), Mem, dynamic arrays, String, keyboard input, threads.", "runtime")
open("jcmp/jc_std.j", "w").write("\n".join(text))
# a file of Library that is not written now is a library that went away (it is downloaded now): delete it
keep = set(["VERSION"] + [n + ".j" for n in unit_names + ["runtime", "cpu", "vector", "matrix"]])
for f in os.listdir("Library"):
    if f not in keep:
        os.remove(os.path.join("Library", f))
open("Library/VERSION", "w").write(open("VERSION").read().strip() + "\n")
PY
